def get_font(size: int, bold: bool = False):
    try:
        font_name = "arialbd.ttf" if bold else "arial.ttf"
        return ImageFont.truetype(font_name, size)
    except Exception:
        return ImageFont.load_default()

def draw_payslip(data: dict) -> Image.Image:
    width, height = 1200, 1600
    img = Image.new("RGB", (width, height), "#ffffff")
    draw = ImageDraw.Draw(img)

    f_title = get_font(34, bold=True)
    f_sub = get_font(18)
    f_header = get_font(22, bold=True)
    f_bold = get_font(20, bold=True)
    f_text = get_font(19)
    f_small = get_font(16)

    # Header Banner
    header_color = data.get("header_color", "#1e293b")
    draw.rectangle([(0, 0), (width, 140)], fill=header_color)
    draw.text((60, 35), data["company"], fill="#ffffff", font=f_title)
    draw.text((60, 85), f"PRIVATE & CONFIDENTIAL — PAYSLIP FOR {data['period'].upper()}", fill="#cbd5e1", font=f_sub)

    # Employee Info Box
    draw.rectangle([(60, 170), (width - 60, 270)], outline="#cbd5e1", width=2, fill="#f8fafc")
    draw.text((80, 190), f"Employee Name : {data['name']}", fill="#0f172a", font=f_bold)
    draw.text((80, 225), f"Employee ID   : {data['emp_id']}", fill="#475569", font=f_text)
    draw.text((650, 190), f"Department    : {data['dept']}", fill="#0f172a", font=f_text)
    draw.text((650, 225), f"Bank A/C      : {data['bank_acc']}", fill="#475569", font=f_text)

    # Earnings & Deductions Tables
    col_mid = width // 2
    y_table_top = 310

    # Section Headers
    draw.rectangle([(60, y_table_top), (col_mid - 20, y_table_top + 45)], fill="#f1f5f9")
    draw.text((80, y_table_top + 10), "EARNINGS", fill="#0f172a", font=f_header)
    draw.text((col_mid - 150, y_table_top + 10), "AMOUNT (₹)", fill="#0f172a", font=f_header)

    draw.rectangle([(col_mid + 20, y_table_top), (width - 60, y_table_top + 45)], fill="#f1f5f9")
    draw.text((col_mid + 40, y_table_top + 10), "DEDUCTIONS", fill="#0f172a", font=f_header)
    draw.text((width - 190, y_table_top + 10), "AMOUNT (₹)", fill="#0f172a", font=f_header)

    # Rows
    y = y_table_top + 60
    earnings = data["earnings"]
    deductions = data["deductions"]
    max_rows = max(len(earnings), len(deductions))

    for i in range(max_rows):
        if i < len(earnings):
            k, v = earnings[i]
            draw.text((80, y), k, fill="#334155", font=f_text)
            draw.text((col_mid - 150, y), f"{v:,.2f}", fill="#0f172a", font=f_bold if "Gross" in k else f_text)
        if i < len(deductions):
            k, v = deductions[i]
            draw.text((col_mid + 40, y), k, fill="#334155", font=f_text)
            draw.text((width - 190, y), f"{v:,.2f}", fill="#0f172a", font=f_bold if "Total" in k else f_text)
        
        draw.line([(60, y + 35), (col_mid - 20, y + 35)], fill="#e2e8f0", width=1)
        draw.line([(col_mid + 20, y + 35), (width - 60, y + 35)], fill="#e2e8f0", width=1)
        y += 50

    # Summary Card / Net Pay Callout
    y_summary = y + 40
    draw.rectangle([(60, y_summary), (width - 60, y_summary + 130)], fill="#eff6ff", outline="#3b82f6", width=2)
    draw.text((90, y_summary + 25), "NET TAKE-HOME PAY", fill="#1e40af", font=f_header)
    draw.text((90, y_summary + 65), f"₹ {data['net_pay']:,.2f}", fill="#1e3a8a", font=get_font(42, bold=True))
    draw.text((col_mid + 40, y_summary + 50), f"(Rupees {data.get('words', 'Only')})", fill="#475569", font=f_small)

    # Footer Disclaimer
    draw.text((60, height - 70), "This is a computer generated salary document for demonstration purposes. Generated by Paylens.", fill="#94a3b8", font=f_small)
    return img

